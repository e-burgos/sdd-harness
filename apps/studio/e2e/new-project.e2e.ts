import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, test, type Page } from '@playwright/test';

const PORT = process.env.E2E_LAUNCHER_PORT ?? '4417';
const STATE_FILE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../.e2e-launcher/state.json');
const COMPOSER = 'Type a message… (/ for commands)';
const EXPECTED_IDEA = 'We are starting wizard-ok: Project generated by the wizard e2e. What is the first feature for webapp, api?';

async function launcherState(): Promise<{ targets: string; token: string }> {
  return JSON.parse(await readFile(STATE_FILE, 'utf8'));
}

async function openLauncher(page: Page): Promise<void> {
  const { token } = await launcherState();
  await page.addInitScript(() => localStorage.setItem('sdd-studio:lang', 'en'));
  await page.goto(`/w/#bridge=${PORT}&token=${token}`);
  await expect(page.getByTestId('launcher-shell')).toBeVisible();
}

async function next(page: Page, step: string): Promise<void> {
  await expect(page.locator(`[data-wizard-step="${step}"]`)).toBeVisible();
  const button = page.getByRole('button', { name: 'Next', exact: true });
  await expect(button).toBeEnabled();
  await button.click();
}

async function walkToSummary(page: Page, name: string): Promise<void> {
  await page.getByTestId('scope-fullstack').click();
  await next(page, 'scope');
  await page.getByTestId('mode-nx').click();
  await page.locator('#wizard-field-project-name').fill(name);
  await page.locator('#wizard-field-project-description').fill('Project generated by the wizard e2e.');
  await next(page, 'shape');
  await page.locator('[data-type-option="react"] button').click();
  await next(page, 'front');
  await page.locator('[data-type-option="nestjs"] button').click();
  await next(page, 'back');
  await expect(page.locator('[data-wizard-step="extras"]')).toBeVisible();
  await next(page, 'extras');
  await expect(page.locator('[data-wizard-step="summary"]')).toBeVisible();
  await expect(page.getByText('Everything is ready to generate.')).toBeVisible();
}

async function setTarget(page: Page, folder: string): Promise<void> {
  await page.locator('#wizard-field-target').fill(folder);
}

const generateButton = (page: Page) => page.getByRole('button', { name: 'Generate', exact: true });

test.describe.configure({ mode: 'serial' });

test('a target with a foreign file is blocked and Generate stays disabled', async ({ page }) => {
  const { targets } = await launcherState();
  const folder = path.join(targets, 'conflicting');
  await mkdir(folder, { recursive: true });
  await writeFile(path.join(folder, 'notes.txt'), 'foreign');
  await openLauncher(page);
  await walkToSummary(page, 'wizard-conflict');
  await setTarget(page, folder);
  await expect(page.getByTestId('target-status')).toHaveAttribute('data-state', 'conflicting');
  await expect(generateButton(page)).toBeDisabled();
});

test('a target with a .git folder asks for confirmation and cancelling generates nothing', async ({ page }) => {
  const { targets } = await launcherState();
  const folder = path.join(targets, 'with-git');
  await mkdir(path.join(folder, '.git'), { recursive: true });
  await openLauncher(page);
  await walkToSummary(page, 'wizard-git');
  await setTarget(page, folder);
  await expect(page.getByTestId('target-status')).toHaveAttribute('data-state', 'tolerated');
  await expect(generateButton(page)).toBeEnabled();
  await generateButton(page).click();
  const dialog = page.getByTestId('confirm-target');
  await expect(dialog).toBeVisible();
  await expect(dialog.getByText('It contains a git repository (.git).')).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Generate in this folder with content' })).not.toBeFocused();
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByTestId('generation-progress')).toHaveCount(0);
});

test('a red gate shows "Generated with errors" and the project can still be opened', async ({ page }) => {
  const { targets } = await launcherState();
  const folder = path.join(targets, 'wizard-red');
  await openLauncher(page);
  await walkToSummary(page, 'wizard-red');
  await setTarget(page, folder);
  await expect(page.getByTestId('target-status')).toHaveAttribute('data-state', 'missing');
  await generateButton(page).click();
  const result = page.getByTestId('generation-result');
  await expect(result).toHaveAttribute('data-variant', 'gate-failed', { timeout: 30_000 });
  await expect(result.getByRole('heading', { name: 'Generated with errors' })).toBeVisible();
  await expect(result.locator('[data-gate-status="fail"]')).toHaveCount(1);
  await expect(result.getByRole('button', { name: 'Open in Studio' })).toBeEnabled();
  await expect(result.getByRole('button', { name: 'Generate in another folder' })).toBeVisible();
});

test('the full wizard generates a project, shows progress and result, and opens it in #general with the idea as draft', async ({ page }) => {
  const { targets } = await launcherState();
  const folder = path.join(targets, 'wizard-ok');
  await openLauncher(page);

  const steps = page.getByRole('list', { name: 'Wizard steps' });
  await expect(steps.locator('[data-step]')).toHaveCount(6);
  await walkToSummary(page, 'wizard-ok');
  await expect(page.getByTestId('preflight')).toHaveAttribute('data-ready', 'true');

  await setTarget(page, folder);
  await expect(page.getByTestId('target-status')).toHaveAttribute('data-state', 'missing');
  await expect(page.getByTestId('target-normalized')).toContainText(folder);
  await generateButton(page).click();

  const result = page.getByTestId('generation-result');
  await expect(result).toHaveAttribute('data-variant', 'success', { timeout: 30_000 });
  await expect(result.getByRole('heading', { name: 'Project generated' })).toBeVisible();
  await expect(result.locator('[data-gate-status="pass"]')).toHaveCount(2);
  const written = JSON.parse(await readFile(path.join(folder, 'harness.config.json'), 'utf8'));
  expect(written.project).toMatchObject({ name: 'wizard-ok', packageScope: '@wizard-ok' });
  expect(written.apps.map((app: { type: string }) => app.type).sort()).toEqual(['nestjs', 'react']);

  await result.getByRole('button', { name: 'Open in Studio' }).click();
  await expect(page.getByTestId('launcher-shell')).toBeHidden({ timeout: 15_000 });
  await expect(page.getByText('studio fixture').first()).toBeVisible();
  await expect(page.getByRole('button', { name: /^general/ })).toBeVisible();
  await expect(page.getByPlaceholder(COMPOSER)).toHaveValue(EXPECTED_IDEA);
  await expect(page).toHaveURL(/\/w\/#?\/?/);
});
