import { fileURLToPath } from 'node:url';
import { defineCommand, runMain } from 'citty';
import pc from 'picocolors';
import { BridgeStartError, DEFAULT_ORIGINS, DEFAULT_WEB_URL, startBridge } from './main';
import { parseEngine, parsePort, parseToken, parseWebUrl } from './cli-options';
import { openBrowser } from './open-browser';
import { BRIDGE_VERSION } from './version';

const main = defineCommand({
  meta: { name: 'sdd-studio', version: BRIDGE_VERSION, description: 'SDD Studio local bridge' },
  args: {
    root: { type: 'string', description: 'Repo root (default: current directory)' },
    port: { type: 'string', description: 'WebSocket port (default: 4320, or the next free one)' },
    engine: { type: 'string', description: 'claude | fake', default: 'claude' },
    'allow-origin': { type: 'string', description: 'Extra allowed origins, comma-separated' },
    'web-url': { type: 'string', description: 'Web app URL', default: DEFAULT_WEB_URL },
    token: { type: 'string', description: 'Fixed pairing token (tests/scripts; a new one is generated by default)' },
    'local-ui': { type: 'boolean', description: 'Serve the web app from the bridge (http://127.0.0.1:<port>/w/)', default: false },
    open: { type: 'boolean', description: 'Open the browser (--no-open to skip)', default: true },
  },
  async run({ args }) {
    const extraOrigins = (args['allow-origin'] ?? '').split(',').map((s) => s.trim()).filter(Boolean);
    try {
      const engine = parseEngine(args.engine);
      const port = args.port === undefined ? 4320 : parsePort(args.port);
      const webUrl = parseWebUrl(args['web-url']);
      const bridge = await startBridge({
        root: args.root ?? process.cwd(),
        port,
        strictPort: args.port !== undefined,
        engine,
        allowedOrigins: [...DEFAULT_ORIGINS, ...extraOrigins],
        webUrl,
        token: args.token !== undefined ? parseToken(args.token) : undefined,
        localUiDir: args['local-ui'] ? fileURLToPath(new URL('./web', import.meta.url)) : undefined,
      });
      const auth = bridge.authMode === 'api-key' ? 'API key (ANTHROPIC_API_KEY)' : 'local Claude Code login';
      console.log(`${pc.bold('SDD Studio')} ${pc.dim(`v${BRIDGE_VERSION}`)} · ${bridge.project}`);
      console.log(`  engine: ${engine === 'fake' ? pc.yellow('fake (no tokens)') : 'Claude Agent SDK'}`);
      console.log(`  auth:   ${auth}`);
      console.log(`  port:   127.0.0.1:${bridge.port}`);
      console.log(`  open:   ${pc.cyan(bridge.url)}`);
      console.log(pc.dim('  Press Ctrl+C to stop.'));
      if (args.open) openBrowser(bridge.url);
      const shutdown = async () => {
        try {
          await bridge.close();
        } catch (error) {
          console.error(pc.red(String(error)));
        }
        process.exit(0);
      };
      process.once('SIGINT', shutdown);
      process.once('SIGTERM', shutdown);
    } catch (error) {
      console.error(pc.red(error instanceof BridgeStartError ? error.message : String(error)));
      process.exit(1);
    }
  },
});

runMain(main);
