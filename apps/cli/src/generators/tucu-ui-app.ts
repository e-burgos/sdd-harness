import { resolve } from "node:path";
import fs from "fs-extra";
import { FRONTEND_VERSIONS } from "./versions.js";

export function tucuUiPackageDeps(type: "react" | "nextjs"): {
  dependencies: Record<string, string>;
  devDependencies: Record<string, string>;
} {
  const dependencies = {
    "@e-burgos/tucu-ui": FRONTEND_VERSIONS["@e-burgos/tucu-ui"],
  };
  if (type === "react") return { dependencies, devDependencies: {} };
  return {
    dependencies,
    devDependencies: {
      tailwindcss: FRONTEND_VERSIONS.tailwindcss,
      "@tailwindcss/postcss": FRONTEND_VERSIONS["@tailwindcss/postcss"],
    },
  };
}

function stylesheet(nodeModulesDir: string, withFonts: boolean): string {
  return [
    "@import 'tailwindcss';",
    "@import '@e-burgos/tucu-ui/theme';",
    ...(withFonts ? ["@import '@e-burgos/tucu-ui/fonts';"] : []),
    `@source '${nodeModulesDir}/@e-burgos/tucu-ui/**/*.mjs';`,
    "",
  ].join("\n");
}

export async function writeViteTucuUiFiles(
  appDir: string,
  name: string,
  nodeModulesDir: string,
): Promise<void> {
  await fs.writeFile(
    resolve(appDir, "src/index.css"),
    stylesheet(nodeModulesDir, true),
    "utf-8",
  );

  await fs.writeFile(
    resolve(appDir, "src/app/app.tsx"),
    `import { LucideIcons, ThemeProvider } from '@e-burgos/tucu-ui';
import { HomePage } from '../pages/HomePage';

const menuItems = [
  {
    name: 'Home',
    path: '/',
    icon: <LucideIcons.LayoutDashboard />,
    component: <HomePage />,
  },
];

export function App() {
  return (
    <ThemeProvider
      logo={{ name: '${name}' }}
      layout="minimal"
      brandColor="Blue"
      menuItems={menuItems}
      isAuthenticated
    />
  );
}
`,
    "utf-8",
  );

  await fs.writeFile(
    resolve(appDir, "src/pages/HomePage.tsx"),
    `import { Button, Card, StatCard } from '@e-burgos/tucu-ui';

export function HomePage() {
  return (
    <div className="space-y-6">
      <Card
        title="${name}"
        description="Replace this page with your first SDD-specified view."
      >
        <Button color="primary">Get started</Button>
      </Card>
      <StatCard title="Active users" value="1,284" subtitle="Last 30 days" />
    </div>
  );
}
`,
    "utf-8",
  );
}

export async function writeNextTucuUiFiles(
  appDir: string,
  name: string,
  nodeModulesDir: string,
): Promise<void> {
  await fs.ensureDir(resolve(appDir, "app"));

  await fs.writeFile(
    resolve(appDir, "app/globals.css"),
    stylesheet(nodeModulesDir, false),
    "utf-8",
  );

  await fs.writeFile(
    resolve(appDir, "postcss.config.mjs"),
    `const config = {
  plugins: {
    '@tailwindcss/postcss': {},
  },
};

export default config;
`,
    "utf-8",
  );

  await fs.writeFile(
    resolve(appDir, "app/layout.tsx"),
    `import type { Metadata } from 'next';
import type { ReactNode } from 'react';
import { LucideIcons } from '@e-burgos/tucu-ui';
import { NextThemeProvider, ThemeModeScript } from '@e-burgos/tucu-ui/next';
import './globals.css';

export const metadata: Metadata = {
  title: '${name}',
  description: 'Generated by @e-burgos/sdd-harness',
};

const menuItems = [
  { name: 'Home', path: '/', icon: <LucideIcons.LayoutDashboard /> },
];

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        <ThemeModeScript defaultMode="system" />
      </head>
      <body>
        <NextThemeProvider
          logo={{ name: '${name}' }}
          layout="admin"
          brandColor="Blue"
          menuItems={menuItems}
        >
          {children}
        </NextThemeProvider>
      </body>
    </html>
  );
}
`,
    "utf-8",
  );

  await fs.writeFile(
    resolve(appDir, "app/page.tsx"),
    `import { Button, Card, StatCard } from '@e-burgos/tucu-ui';

export default function Home() {
  return (
    <div className="space-y-6">
      <Card
        title="${name}"
        description="Start editing app/page.tsx"
      >
        <Button color="primary">Get started</Button>
      </Card>
      <StatCard title="Active users" value="1,284" subtitle="Last 30 days" />
    </div>
  );
}
`,
    "utf-8",
  );
}
